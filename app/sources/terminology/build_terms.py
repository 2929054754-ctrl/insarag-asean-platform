# Build final list
# ──────────────────────────────────────────────────────────────────
def main():
    rows = []
    seen_en = set()

    def add(zh, en, defi, chapter, url, domain, status):
        # Normalize en key for dedup
        en_key = re.sub(r'\s+', ' ', en).strip().lower()
        # Strip parenthetical acronym already in main
        if en_key in seen_en:
            return False
        seen_en.add(en_key)
        rows.append({
            "zh": zh, "en": en, "def": defi,
            "domain": domain, "chapter": chapter,
            "url": url, "status": status,
        })
        return True

    # A. Original 54 — these are authoritative (already curated)
    for zh, en, defi, chap, url, dom in ORIGINAL:
        add(zh, en, defi, chap, url, dom, "已审核")

    # B. Extra abbreviations from official list
    for abbr, zh, en_full, defi, dom in ABBREVS_EXTRA:
        en = f"{abbr} ({en_full})"
        add(zh, en, defi, "常用缩略语（第3-6页）", ZH_PDF, dom, "已审核")

    # C. UNDRR glossary (official Chinese translation in 附件D)
    for zh, en, defi, chap in GLOSSARY:
        add(zh, en, defi, chap, ZH_PDF, "灾害风险管理", "已审核")

    # D. Operational / role / technical / marking / UN / GDACS terms
    # These are extracted from chapters — mark 待审核 unless directly from official lists
    for item in OPERATIONAL:
        zh, en, defi, dom, chap = item
        # If chapter references 常用缩略语 or explicit official list, mark 已审核
        status = "待审核"
        if chap.startswith("常用缩略语"):
            status = "已审核"
        add(zh, en, defi, chap, ZH_PDF if chap != GDACS_URL and chap != "https://ahacentre.org/" else chap, dom, status)

    # ── Write xlsx ──
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "INSARAG术语库"
    headers = ["id", "中文术语", "英文术语", "释义", "领域分类", "所属章节", "来源链接", "审核状态"]
    ws.append(headers)

    # Header style
    hdr_font = Font(bold=True, color="FFFFFF")
    hdr_fill = PatternFill("solid", fgColor="1F4E79")
    thin = Side(style="thin", color="CCCCCC")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    for col in range(1, len(headers)+1):
        c = ws.cell(row=1, column=col)
        c.font = hdr_font
        c.fill = hdr_fill
        c.alignment = Alignment(horizontal="center", vertical="center")
        c.border = border

    for i, r in enumerate(rows, start=1):
        ws.append([i, r["zh"], r["en"], r["def"], r["domain"], r["chapter"], r["url"], r["status"]])
        for col in range(1, len(headers)+1):
            cell = ws.cell(row=i+1, column=col)
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = border

    # Column widths
    widths = [6, 28, 42, 60, 16, 28, 40, 10]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    ws.freeze_panes = "A2"

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "INSARAG术语库.xlsx")
    wb.save(out)

    # Stats
    from collections import Counter
    dom_count = Counter(r["domain"] for r in rows)
    status_count = Counter(r["status"] for r in rows)
    src_count = Counter()
    for r in rows:
        if "insarag.org" in r["url"]:
            src_count["INSARAG中英文指南PDF"] += 1
        elif "gdacs.org" in r["url"]:
            src_count["GDACS"] += 1
        elif "undrr.org" in r["url"]:
            src_count["UNDRR术语库"] += 1
        elif "ahacentre" in r["url"]:
            src_count["AHA Centre"] += 1
        elif "vosocc" in r["url"]:
            src_count["VOSOCC"] += 1
        elif "insarag.org/asia" in r["url"] or "insarag.org/africa" in r["url"] or "insarag.org/americas" in r["url"] or "insarag.org/exercise" in r["url"]:
            src_count["INSARAG官网"] += 1
        else:
            src_count["其他/指南章节"] += 1

    print(f"Total terms: {len(rows)}")
    print(f"\nBy domain:")
    for k, v in dom_count.most_common():
        print(f"  {k}: {v}")
    print(f"\nBy status:")
    for k, v in status_count.most_common():
        print(f"  {k}: {v}")
    print(f"\nBy source:")
    for k, v in src_count.most_common():
        print(f"  {k}: {v}")
    print(f"\nOutput: {out}")

if __name__ == "__main__":
    main()
